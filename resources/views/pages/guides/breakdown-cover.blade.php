<h3>How do I know if my driving licence has expired?</h3>



<p>In order to confirm that your drivers licence is expired, you&#8217;ll need to refer to point 4b on the photo side of your current licence. If your licence is expired sooner than you remember don&#8217;t worry, you can still continue to drive your car but you will still need to renew your expired licence.</p>



<p>You can renew your <a href="https://www.gov.uk/renew-driving-licence">UK driving licence online</a> at the official gov.uk website or you can get the physical &#8216;<strong>D1 pack</strong>&#8216; from your local post office.</p>



<h3>Why has my driving licence expired?</h3>



<p>As physical appearances can change over time, it is a requirement to renew a photocard licence <strong>every 10 years</strong> in the UK. This is to ensure that police and authorities have the most accurate and up-to-date image of you in the event your licence needs to be verified. You will also need to update any name and address changes since your last licence. </p>



<p>The current cost for renewing your licence online is <strong>£14</strong>. </p>



<h3>Can I still drive if my licence is expired?</h3>



<p>Yes, you can still drive if you are waiting for your renewed driving licence to arrive. Simply inform the <a href="https://www.quotezone.co.uk/car-insurance/police-officers">police</a> or relevant authorities that you are in the process of renewing your licence if they ask you to produce it. You may be asked to present your renewed licence at your local police station as proof when it arrives. You must legally keep your driving licence up to date, so do not simply drive on an expired licence without the intention of renewing it as this is illegal and can lead to up to 6 demerit points and a fine not exceeding £1000.</p>



<h3>What to do if my driving licence has expired</h3>



<p>Driving without a valid licence in the UK can result in <a href="https://www.quotezone.co.uk/car-insurance/guides/how-much-three-penalty-points-cost-insurance">six penalty points</a> and a fine of up to but not exceeding £1,000. You can expect to receive a reminder from the DVLA, or DVA in <a href="https://www.quotezone.co.uk/car-insurance/northern-ireland">Northern Ireland</a>, to your last registered address on file in the run-up to your renewal date.</p>



<p>When your driving licence expires you must renew it as soon as possible. Since authorities are aware that it can take in excess of 3 weeks for some drivers to receive their new licence. </p>



<p>If the police wish to view your driver&#8217;s licence while you are currently waiting for your renewed licence to arrive, simply explain the situation to them. You may still be asked to present your renewed licence to your local police station when it arrives to verify your story. Generally, police officers will understand why you can&#8217;t produce a licence whilst it is being renewed so there is no need to worry thinking you will not be able to drive until your renewed licence arrives.</p>



<p>Here are some key points to remember when your licence expires</p>



<ul>
<li>It is your legal responsibility to ensure your driver&#8217;s licence is up to date.</li>



<li>In order to renew your licence online, you&#8217;ll need a UK passport or the document you used to confirm your online immigration status.</li>



<li>Renewing your licence costs £14 &#8211; There&#8217;s no fee if you are over 70 or have a medical short-period licence.</li>



<li>Your driving licence may take up to <strong>3 weeks</strong> to arrive but in some cases this time may be longer.</li>



<li><strong>Do not lie</strong> to police about renewing your licence if you haven&#8217;t, it&#8217;s illegal and you will likely be asked to provide proof.</li>



<li>You can renew your licence either online or at your local post office.</li>
</ul>



<h3>What do I need to renew my UK licence?</h3>



<p>To start the renewal process you&#8217;ll need a few things at hand in order for your application to be processed.</p>



<ul>
<li><strong>UK passport</strong> &#8211; Either current or expired within the past 12 months. </li>



<li>The documents used to set up your online immigration status.</li>



<li>All <strong>addresses</strong> over the last 3 years.</li>



<li><strong>Current driving licence</strong> &#8211; If you have it.</li>



<li><strong>National Insurance number</strong> &#8211; If known. </li>
</ul>



<p>You will also need to be a UK resident and not currently disqualified from driving in order to renew your UK licence.</p>

